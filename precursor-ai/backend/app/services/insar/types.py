"""Shared types for Phase 3 InSAR processing. Pure data; no I/O."""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from enum import StrEnum
from typing import Any


class ProductKind(StrEnum):
    GUNW = "GUNW"
    GSLC = "GSLC"
    GCOV = "GCOV"
    S1_SLC = "S1_SLC"
    UNKNOWN = "UNKNOWN"


class RunStatus(StrEnum):
    PENDING = "PENDING"
    QUEUED = "QUEUED"
    INSPECTING = "INSPECTING"
    PREPROCESSING = "PREPROCESSING"
    INTERFEROGRAM_GENERATION = "INTERFEROGRAM_GENERATION"
    PHASE_UNWRAPPING = "PHASE_UNWRAPPING"
    DISPLACEMENT_CALCULATION = "DISPLACEMENT_CALCULATION"
    QUALITY_CHECK = "QUALITY_CHECK"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"
    BLOCKED_MISSING_INPUT = "BLOCKED_MISSING_INPUT"


TERMINAL = {RunStatus.COMPLETED, RunStatus.FAILED, RunStatus.CANCELLED, RunStatus.BLOCKED_MISSING_INPUT}


class DataOrigin(StrEnum):
    """Where the input came from. Never upgrade this label silently."""

    REAL_SATELLITE = "REAL_SATELLITE"  # a registered Phase 2 acquisition whose file was downloaded from NASA/ASF
    SYNTHETIC_FIXTURE = "SYNTHETIC_FIXTURE"  # generated by this repo for tests/demos; carries a marker attribute
    LOCAL_UNVERIFIED = "LOCAL_UNVERIFIED"  # a local file of unknown provenance


class ProductType(StrEnum):
    LOS_DISPLACEMENT = "LOS_DISPLACEMENT"
    COHERENCE = "COHERENCE"
    LOS_VELOCITY = "LOS_VELOCITY"


class ProcessingError(Exception):
    """A required scientific check failed. Processing must stop, never continue silently."""


class BlockedMissingInput(Exception):
    """Input or external tool is not available; the run ends BLOCKED_MISSING_INPUT."""


@dataclass
class DatasetInfo:
    path: str
    shape: tuple[int, ...]
    dtype: str
    chunks: tuple[int, ...] | None = None
    units: str | None = None
    fill_value: float | None = None


@dataclass
class GridInfo:
    """Georeferencing of one raster grid (pixel-centre coordinate vectors -> affine)."""

    width: int
    height: int
    epsg: int | None
    x0: float  # centre of first column
    y0: float  # centre of first row
    dx: float
    dy: float  # negative for north-up grids

    def transform_tuple(self) -> tuple[float, float, float, float, float, float]:
        """Affine (a, b, c, d, e, f) of the pixel corner grid."""
        return (self.dx, 0.0, self.x0 - self.dx / 2, 0.0, self.dy, self.y0 - self.dy / 2)


@dataclass
class InspectionReport:
    file_name: str
    file_size_bytes: int
    file_format: str  # hdf5 | zip | safe | unknown
    product_kind: ProductKind
    data_origin: DataOrigin
    product_version: str | None = None
    roles: dict[str, str] = field(default_factory=dict)  # role -> dataset path (what was actually found)
    ambiguous: dict[str, list[str]] = field(default_factory=dict)
    datasets: list[DatasetInfo] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)
    grid: GridInfo | None = None
    reference_time: datetime | None = None
    secondary_time: datetime | None = None
    wavelength_m: float | None = None
    orbit_direction: str | None = None
    perpendicular_baseline_m: float | None = None
    missing: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    supported_stages: list[str] = field(default_factory=list)
    displacement_supported: bool = False
    displacement_blockers: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        def conv(v: Any) -> Any:
            if isinstance(v, datetime):
                return v.isoformat()
            if isinstance(v, StrEnum):
                return v.value
            if hasattr(v, "__dataclass_fields__"):
                return {k: conv(getattr(v, k)) for k in v.__dataclass_fields__}
            if isinstance(v, dict):
                return {k: conv(x) for k, x in v.items()}
            if isinstance(v, (list, tuple)):
                return [conv(x) for x in v]
            return v

        return conv(self)  # type: ignore[no-any-return]


@dataclass
class ProcessingConfig:
    """Stored with every run. Defaults are deliberately conservative."""

    polarization: str | None = None  # None -> first available, with a warning when several exist
    coherence_threshold: float | None = None  # None -> do not mask by coherence
    use_connected_components_mask: bool = False
    compute_velocity: bool = True
    block_rows: int = 256
    keep_intermediates: bool = False

    def to_dict(self) -> dict[str, Any]:
        return {k: getattr(self, k) for k in self.__dataclass_fields__}


@dataclass
class OutputFile:
    kind: ProductType
    path: str  # absolute while processing; stored relative to data_root in the DB
    units: str
    nodata: float | None
    width: int
    height: int
    crs: str | None
    stats: dict[str, Any]
    extra: dict[str, Any] = field(default_factory=dict)


@dataclass
class ProcessingResult:
    outputs: list[OutputFile] = field(default_factory=list)
    stats: dict[str, Any] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)
