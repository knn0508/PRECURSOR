"""Product adapters inspect a file and say honestly what can be done with it."""
from __future__ import annotations

from abc import ABC, abstractmethod
from pathlib import Path

import h5py
import numpy as np

from app.core.synthetic_guard import refuse_if_synthetic
from app.services.insar import hdf
from app.services.insar.phase_to_displacement import wavelength_from_frequency
from app.services.insar.types import DataOrigin, DatasetInfo, GridInfo, InspectionReport, ProductKind

STAGE_INSPECT, STAGE_PRE, STAGE_DISP, STAGE_QC = "INSPECTING", "PREPROCESSING", "DISPLACEMENT_CALCULATION", "QUALITY_CHECK"


class ProductAdapter(ABC):
    kind: ProductKind

    @abstractmethod
    def inspect(self, path: Path, origin: DataOrigin) -> InspectionReport: ...


class NISARHDF5Adapter(ProductAdapter):
    """Shared HDF5 inspection. Subclasses fill the product-specific roles and blockers."""

    group: str  # e.g. "GUNW"

    def inspect(self, path: Path, origin: DataOrigin) -> InspectionReport:
        rep = InspectionReport(
            file_name=path.name, file_size_bytes=path.stat().st_size, file_format="hdf5",
            product_kind=self.kind, data_origin=origin,
        )
        with h5py.File(path, "r") as f:
            refuse_if_synthetic(f.attrs.get(hdf.SYNTHETIC_MARKER) is not None, ValueError, path.name)
            if f.attrs.get(hdf.SYNTHETIC_MARKER) is not None:
                rep.data_origin = DataOrigin.SYNTHETIC_FIXTURE
                rep.warnings.append("SYNTHETIC FIXTURE: generated by this repository, not a satellite observation")
            idx = hdf.index_datasets(f)
            self._identification(f, idx, rep)
            self._specific(f, idx, rep)
        return rep

    # -- identification (common) ---------------------------------------------------------
    def _first(self, f: h5py.File, idx: dict, name: str, prefer: str = "identification"):
        paths = idx.get(name, [])
        paths = sorted(paths, key=lambda p: prefer not in p)
        return hdf.read_scalar(f, paths[0]) if paths else None

    def _identification(self, f: h5py.File, idx: dict, rep: InspectionReport) -> None:
        ptype = self._first(f, idx, "productType")
        if ptype is None:
            rep.missing.append("identification/productType")
        elif str(ptype).upper() != self.group:
            rep.warnings.append(f"identification/productType is {ptype!r} but the file layout is {self.group}")
        rep.product_version = self._str(self._first(f, idx, "productVersion"))
        if rep.product_version is None:
            rep.missing.append("identification/productVersion")
        rep.orbit_direction = self._str(self._first(f, idx, "orbitPassDirection"))
        if rep.orbit_direction is None:
            rep.missing.append("identification/orbitPassDirection")
        trk = self._first(f, idx, "trackNumber")
        if trk is not None:
            rep.metadata["track_number"] = trk
        rep.reference_time = hdf.parse_time(self._first(f, idx, "referenceZeroDopplerStartTime"))
        rep.secondary_time = hdf.parse_time(self._first(f, idx, "secondaryZeroDopplerStartTime"))

    @staticmethod
    def _str(v) -> str | None:
        return str(v) if v is not None and v != "" else None

    # -- shared helpers -------------------------------------------------------------------
    def _info(self, f: h5py.File, path: str) -> DatasetInfo:
        ds = f[path]
        return DatasetInfo(path=path, shape=tuple(ds.shape), dtype=str(ds.dtype), chunks=ds.chunks,
                           units=hdf.units_of(ds), fill_value=hdf.fill_value_of(ds))

    def _grid(self, f: h5py.File, ds_path: str, rep: InspectionReport, blockers: list[str]) -> GridInfo | None:
        """Georeferencing from pixel-centre coordinate vectors found next to the raster."""
        ds = f[ds_path]
        if ds.ndim != 2:
            blockers.append(f"{ds_path} is not 2-D")
            return None
        h, w = ds.shape
        xp, yp = hdf.nearest(f, ds_path, "xCoordinates"), hdf.nearest(f, ds_path, "yCoordinates")
        if xp is None or yp is None:
            blockers.append("x/y coordinate vectors not found: cannot georeference")
            rep.missing.append("xCoordinates/yCoordinates")
            return None
        x, y = f[xp][()], f[yp][()]
        if len(x) != w or len(y) != h:
            blockers.append(f"coordinate vectors ({len(x)}, {len(y)}) do not match raster shape ({w}, {h})")
            return None
        if w < 2 or h < 2 or not (np.isfinite(x[:2]).all() and np.isfinite(y[:2]).all()):
            blockers.append("coordinate vectors too short or non-finite")
            return None
        dx, dy = float(x[1] - x[0]), float(y[1] - y[0])
        if dx == 0 or dy == 0 or not np.allclose(np.diff(x[: min(w, 64)]), dx, rtol=1e-6) \
                or not np.allclose(np.diff(y[: min(h, 64)]), dy, rtol=1e-6):
            blockers.append("coordinate spacing is zero or irregular: not a regular grid")
            return None
        epsg = self._epsg(f, ds_path)
        if epsg is None:
            blockers.append("projection (EPSG) not found: CRS unknown")
            rep.missing.append("projection")
        return GridInfo(width=w, height=h, epsg=epsg, x0=float(x[0]), y0=float(y[0]), dx=dx, dy=dy)

    def _epsg(self, f: h5py.File, ds_path: str) -> int | None:
        pp = hdf.nearest(f, ds_path, "projection")
        if pp is None:
            return None
        ds = f[pp]
        for key in ("epsg_code", "epsg", "EPSG"):
            if key in ds.attrs:
                try:
                    return int(np.asarray(ds.attrs[key]).ravel()[0])
                except (TypeError, ValueError):
                    pass
        try:
            v = int(np.asarray(ds[()]).ravel()[0])
            return v if v > 0 else None
        except (TypeError, ValueError, IndexError):
            return None

    def _wavelength(self, f: h5py.File, idx: dict, near: str, rep: InspectionReport, blockers: list[str]) -> None:
        for name in ("centerFrequency", "processedCenterFrequency"):
            p = hdf.nearest(f, near, name) or (idx.get(name) or [None])[0]
            if p:
                try:
                    freq = float(np.asarray(f[p][()]).ravel()[0])
                    rep.wavelength_m = wavelength_from_frequency(freq)
                    rep.metadata["center_frequency_hz"] = freq
                    rep.metadata["wavelength_source"] = p
                    return
                except (ValueError, TypeError, IndexError) as exc:
                    blockers.append(f"radar frequency/wavelength invalid: {exc}")
                    return
        blockers.append("radar centre frequency not found: wavelength unknown")
        rep.missing.append("centerFrequency")

    def _specific(self, f: h5py.File, idx: dict, rep: InspectionReport) -> None:
        raise NotImplementedError
